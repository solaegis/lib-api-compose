#!/usr/bin/env lua
-- ZOS API drift check for LibApiCompose (plain Lua 5.1+, run on the host).
--
-- Source of truth: the "BEGIN ZOS API" .. "END ZOS API" block of .luacheckrc. Luacheck already
-- guarantees every global the library reads is listed there; this script guarantees the list
-- is real and current:
--   1. every listed name is still used in a manifest-listed src file,
--   2. src/Symbols.lua (read by LAC.SelfTest in game) matches the list,
--   3. with an ESOUIDocumentation.txt: every name exists in that API version, and every mock
--      stub of a multi-return function carries a matching "-- returns: N" annotation.
--
-- Usage:
--   lua scripts/zos-api.lua check [path/to/ESOUIDocumentation.txt] [--strict]
--   lua scripts/zos-api.lua write        (regenerate src/Symbols.lua)
--   lua scripts/zos-api.lua list

local MANIFEST = "LibApiCompose.txt"
local LUACHECKRC = ".luacheckrc"
local SYMBOLS = "src/Symbols.lua"
local MOCK = "tests/mock/eso.lua"

local function readFile(path)
    local f = io.open(path, "rb")
    if not f then
        return nil
    end
    local content = f:read("*a")
    f:close()
    return content
end

local function fail(message)
    io.stderr:write("❌ " .. message .. "\n")
    os.exit(1)
end

local function listedSymbols()
    local rc = readFile(LUACHECKRC) or fail("cannot read " .. LUACHECKRC)
    local block = rc:match("%-%- BEGIN ZOS API(.-)%-%- END ZOS API")
    if not block then
        fail(LUACHECKRC .. " has no BEGIN ZOS API / END ZOS API block")
    end
    local names = {}
    for name in block:gmatch('"([%w_]+)"') do
        names[#names + 1] = name
    end
    local sorted = {}
    for i = 1, #names do
        sorted[i] = names[i]
    end
    table.sort(sorted)
    for i = 1, #names do
        if names[i] ~= sorted[i] then
            fail(string.format("%s ZOS API block is not sorted (first out-of-order entry: %s)", LUACHECKRC, names[i]))
        end
        if i > 1 and names[i] == names[i - 1] then
            fail(string.format("%s ZOS API block lists %s twice", LUACHECKRC, names[i]))
        end
    end
    return names
end

local function sourceFiles()
    local manifest = readFile(MANIFEST) or fail("cannot read " .. MANIFEST)
    local files = {}
    for line in manifest:gmatch("[^\r\n]+") do
        local path = line:match("^%s*([%w_/%.%-]+%.lua)%s*$")
        if path then
            files[#files + 1] = path
        end
    end
    return files
end

-- Event names are looked up dynamically (_G["EVENT_..."]), so luacheck cannot see them.
local function eventNames(sources)
    local seen, events = {}, {}
    for _, source in pairs(sources) do
        for name in source:gmatch('"(EVENT_[A-Z0-9_]+)"') do
            if not seen[name] then
                seen[name] = true
                events[#events + 1] = name
            end
        end
    end
    table.sort(events)
    return events
end

local function symbolsFileContent(names)
    local lines = {
        "-- GENERATED by scripts/zos-api.lua from the ZOS API block of .luacheckrc — do not edit.",
        "-- Regenerate with `task dev:zos:write`. Read by LAC.SelfTest().",
        "",
        "LibApiCompose._internal.ZOS_SYMBOLS = {",
    }
    for i = 1, #names do
        lines[#lines + 1] = string.format('    "%s",', names[i])
    end
    lines[#lines + 1] = "}"
    lines[#lines + 1] = ""
    return table.concat(lines, "\n")
end

-- name -> number of documented return values (0 when the doc lists none).
local function parseDoc(path)
    local doc = readFile(path) or fail("cannot read API documentation: " .. path)
    local version = doc:match("API Version (%d+)")
    local known = {}
    local pending = nil
    for line in doc:gmatch("[^\r\n]+") do
        local name = line:match("^%* ([%w_]+)")
        if name then
            known[name] = known[name] or 0
            pending = line:match("^%* [%w_]+%(") and name or nil
        elseif pending then
            local returns = line:match("^%*%* _Returns:_ (.+)$")
            if returns then
                local _, commas = returns:gsub(", ", "")
                known[pending] = commas + 1
            end
            if not line:match("^%*%* _Uses variable returns") then
                pending = line:match("^%*%*") and pending or nil
            end
        end
    end
    return known, version
end

local function manifestApiVersion()
    local manifest = readFile(MANIFEST) or ""
    return manifest:match("## APIVersion:%s*(%d+)")
end

local function checkMock(known, problems)
    local mock = readFile(MOCK)
    if not mock then
        return
    end
    local previous = ""
    for line in mock:gmatch("[^\n]*") do
        local name = line:match("^function _G%.([%w_]+)%(")
        if name then
            local documented = known[name]
            if documented == nil then
                problems[#problems + 1] =
                    string.format("%s stubs %s, which is not in the API documentation", MOCK, name)
            elseif documented > 1 then
                local annotated = tonumber(previous:match("^%-%- returns: (%d+)%s*$"))
                if annotated ~= documented then
                    problems[#problems + 1] = string.format(
                        '%s: %s returns %d values in the API; the line above the stub must be "-- returns: %d" (found %s)',
                        MOCK,
                        name,
                        documented,
                        documented,
                        annotated and tostring(annotated) or "no annotation"
                    )
                end
            end
        end
        if line ~= "" then
            previous = line
        end
    end
end

local command = arg[1]
local names = listedSymbols()
local files = sourceFiles()
local sources = {}
for _, path in ipairs(files) do
    if path ~= SYMBOLS then
        sources[path] = readFile(path) or fail("manifest lists a missing file: " .. path)
    end
end
local all = {}
for _, name in ipairs(names) do
    all[#all + 1] = name
end
for _, name in ipairs(eventNames(sources)) do
    all[#all + 1] = name
end
table.sort(all)

if command == "list" then
    print(table.concat(all, "\n"))
    os.exit(0)
elseif command == "write" then
    local f = assert(io.open(SYMBOLS, "wb"))
    f:write(symbolsFileContent(all))
    f:close()
    print(string.format("✅ Wrote %s (%d symbols)", SYMBOLS, #all))
    os.exit(0)
elseif command ~= "check" then
    fail("usage: lua scripts/zos-api.lua check [ESOUIDocumentation.txt] [--strict] | write | list")
end

local docPath, strict = nil, false
for i = 2, #arg do
    if arg[i] == "--strict" then
        strict = true
    elseif arg[i] ~= "" then
        docPath = arg[i]
    end
end

local problems = {}

-- 1. Every listed name is still used.
for _, name in ipairs(names) do
    local used = false
    for _, source in pairs(sources) do
        if source:find("%f[%w_]" .. name .. "%f[^%w_]") then
            used = true
            break
        end
    end
    if not used then
        problems[#problems + 1] = string.format("%s lists %s but no src file uses it (remove it)", LUACHECKRC, name)
    end
end

-- 2. Generated symbol table is current and loaded by the manifest.
if readFile(SYMBOLS) ~= symbolsFileContent(all) then
    problems[#problems + 1] = SYMBOLS .. " is out of date (run: task dev:zos:write)"
end
local inManifest = false
for _, path in ipairs(files) do
    inManifest = inManifest or path == SYMBOLS
end
if not inManifest then
    problems[#problems + 1] = MANIFEST .. " does not list " .. SYMBOLS
end

-- 3. Against the API documentation.
if docPath then
    local known, docVersion = parseDoc(docPath)
    local wanted = manifestApiVersion()
    if docVersion ~= wanted then
        local message = string.format(
            "API documentation is for %s but the manifest's first APIVersion is %s",
            tostring(docVersion),
            tostring(wanted)
        )
        if strict then
            problems[#problems + 1] = message
        else
            print("⚠️  " .. message)
        end
    end
    for _, name in ipairs(all) do
        if known[name] == nil then
            problems[#problems + 1] = string.format("%s does not exist in API %s", name, tostring(docVersion))
        end
    end
    checkMock(known, problems)
    print(string.format("   checked %d symbols against API %s", #all, tostring(docVersion)))
else
    local message = "no API documentation given — existence and mock-arity checks skipped"
    if strict then
        problems[#problems + 1] = message
    else
        print("⚠️  " .. message)
    end
end

if #problems > 0 then
    for _, problem in ipairs(problems) do
        io.stderr:write("❌ " .. problem .. "\n")
    end
    os.exit(1)
end
print("✅ ZOS API symbols are consistent")
